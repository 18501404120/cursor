def _fix_m1_order_redundancy(t: str) -> str:
    return t.replace("**订单与履约管理订单**", "**订单与履约管理**")


def _replace_remaining_m_codes(t: str) -> str:
    def repl(m: re.Match[str]) -> str:
        n = int(m.group(1))
        if n in NAMES:
            return NAMES[n]
        return m.group(0)

    return re.sub(r"(?<![0-9A-Za-z_])M(13|11|7|6|5|4|3|2|1)(?![0-9])", repl, t)


def _normalize_m01(t: str) -> str:
    return re.sub(r"\bM0([1-7])\b", lambda m: NAMES[int(m.group(1))], t)


